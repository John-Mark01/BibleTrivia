$function$;

create or replace function public.get_available_quizzes_for_user_for_topic(
    user_id_param text, topic_id_param text,
    limit_param integer default null::integer, offset_param integer default 0)
returns json language plpgsql security definer as $function$
declare result json;
begin
    select json_agg(quiz_data) into result
    from (
        select json_build_object(
            'quiz', json_build_object(
                'id', q.id, 'name', q.name, 'time_to_complete', q.time_to_complete,
                'status', q.status, 'difficulty', q.difficulty,
                'total_points', q.total_points, 'topic_id', q.topic_id),
            'questions', coalesce((
                select json_agg(json_build_object(
                    'question', json_build_object(
                        'id', quest.id, 'text', quest.text,
                        'explaination', quest.explaination, 'quiz_id', quest.quiz_id),
                    'answers', coalesce((
                        select json_agg(json_build_object(
                            'id', a.id, 'text', a.text,
                            'question_id', a.question_id, 'is_correct', a.is_correct))
                        from answers a where a.question_id = quest.id), '[]'::json)))
                from questions quest where quest.quiz_id = q.id), '[]'::json)
        ) as quiz_data
        from quizzez q
        where q.topic_id = topic_id_param::int8
        and not exists (
            select 1 from user_quiz_sessions uqs
            where uqs.user_id = user_id_param::uuid and uqs.quiz_id = q.id
            and uqs.status in ('in_progress', 'completed'))
        order by q.id
        limit coalesce(limit_param, 1000000) offset offset_param
    ) subquery;
    return coalesce(result, '[]'::json);
end;
$function$;

create or replace function public.get_user_completed_quizzes_by_topic(
    user_id_param text, topic_id_param text,
    limit_param integer default null::integer, offset_param integer default 0)
returns json language plpgsql security definer as $function$
declare result json;
begin
    select json_agg(quiz_data) into result
    from (
        select json_build_object(
            'session', json_build_object(
                'id', uqs.id, 'user_id', uqs.user_id::text, 'quiz_id', uqs.quiz_id,
                'started_at', uqs.started_at, 'completed_at', uqs.completed_at,
                'status', uqs.status, 'attempt_number', uqs.attempt_number,
                'percentage', uqs.percentage, 'passed', uqs.passed,
                'time_spent_seconds', uqs.time_spent_seconds),
            'quiz', json_build_object(
                'id', q.id, 'name', q.name, 'time_to_complete', q.time_to_complete,
                'status', q.status, 'difficulty', q.difficulty,
                'total_points', q.total_points, 'topic_id', q.topic_id),
            'questions', coalesce((
                select json_agg(json_build_object(
                    'question', json_build_object(
                        'id', quest.id, 'text', quest.text,
                        'explaination', quest.explaination, 'quiz_id', quest.quiz_id),
                    'answers', coalesce((
                        select json_agg(json_build_object(
                            'id', a.id, 'text', a.text,
                            'question_id', a.question_id, 'is_correct', a.is_correct))
                        from answers a where a.question_id = quest.id), '[]'::json)))
                from questions quest where quest.quiz_id = q.id), '[]'::json)
        ) as quiz_data
        from user_quiz_sessions uqs
        inner join quizzez q on uqs.quiz_id = q.id
        where uqs.user_id = user_id_param::uuid
        and uqs.status = 'completed'
        and q.topic_id = topic_id_param::int8
        order by uqs.completed_at desc
        limit coalesce(limit_param, 1000000) offset offset_param
    ) subquery;
    return coalesce(result, '[]'::json);
end;
$function$;

create or replace function public.get_user_quiz_stats(user_id_param uuid)
returns json language plpgsql security definer as $function$
declare result json;
begin
    select json_build_object(
        'total_started', count(*),
        'total_completed', count(*) filter (where status = 'completed'),
        'total_in_progress', count(*) filter (where status = 'in_progress'),
        'total_passed', count(*) filter (where status = 'completed' and passed = true),
        'average_score', avg(percentage) filter (where status = 'completed'),
        'total_time_spent_seconds', sum(time_spent_seconds) filter (where status = 'completed'))
    into result
    from user_quiz_sessions where user_id = user_id_param;
    return result;
end;
$function$;

create or replace function public.mark_abandoned_sessions()
returns integer language plpgsql security definer as $function$
declare updated_count int;
begin
    update user_quiz_sessions
    set status = 'abandoned', updated_at = now()
    where status = 'in_progress' and last_saved_at < now() - interval '7 days';
    get diagnostics updated_count = row_count;
    return updated_count;
end;
$function$;

create or replace function public.reset_expired_streaks()
returns setof public.user_streaks language plpgsql security definer as $function$
begin
    return query
    update user_streaks set current_streak = 0
    where last_visit < now() - interval '24 hours'
    returning *;
end;
$function$;

create or replace function public.save_quiz_progress(
    session_id_param bigint, answers_param text, is_completed boolean default false)
returns json language plpgsql security definer as $function$
declare
    session_record record;
    answers_jsonb jsonb;
    answered_count int;
    correct_count int;
    incorrect_count int;
    percentage_val numeric(5,2);
    passed_val bool;
    result json;
begin
    answers_jsonb := answers_param::jsonb;
    select * into session_record from user_quiz_sessions where id = session_id_param;
    if not found then
        raise exception 'Session not found';
    end if;
    answered_count := jsonb_array_length(answers_jsonb);
    select
        count(*) filter (where (value->>'is_correct')::boolean = true),
        count(*) filter (where (value->>'is_correct')::boolean = false)
    into correct_count, incorrect_count
    from jsonb_array_elements(answers_jsonb);
    if is_completed then
        percentage_val := (correct_count::numeric / session_record.total_questions) * 100;
        passed_val := percentage_val >= 70.0;
        update user_quiz_sessions set
            answers = answers_jsonb, status = 'completed', completed_at = now(),
            last_saved_at = now(), answered_questions = answered_count,
            correct_answers = correct_count, incorrect_answers = incorrect_count,
            current_score = correct_count, final_score = correct_count,
            percentage = percentage_val, passed = passed_val,
            time_spent_seconds = extract(epoch from (now() - started_at))::int8,
            updated_at = now()
        where id = session_id_param;
    else
        update user_quiz_sessions set
            answers = answers_jsonb, last_saved_at = now(),
            answered_questions = answered_count, correct_answers = correct_count,
            incorrect_answers = incorrect_count, current_score = correct_count,
            updated_at = now()
        where id = session_id_param;
    end if;
    select json_build_object(
        'id', id, 'status', status, 'answered_questions', answered_questions,
        'correct_answers', correct_answers, 'percentage', percentage, 'passed', passed)
    into result from user_quiz_sessions where id = session_id_param;
    return result;
end;
$function$;

