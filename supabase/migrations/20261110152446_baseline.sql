create or replace function public.check_and_update_streak(user_uuid uuid)
returns public.user_streaks language plpgsql security definer as $function$
declare
    streak_record public.user_streaks;
    hours_since_last_visit float;
begin
    select * into streak_record from public.user_streaks where user_id = user_uuid;
    if not found then
        insert into public.user_streaks (user_id, current_streak, last_visit)
        values (user_uuid, 1, now()) returning * into streak_record;
        update public.users set streak = 1 where id = user_uuid;
        return streak_record;
    end if;
    hours_since_last_visit := extract(epoch from (now() - streak_record.last_visit)) / 3600;
    if hours_since_last_visit > 24 then
        update public.user_streaks set current_streak = 1, last_visit = now()
        where user_id = user_uuid returning * into streak_record;
        update public.users set streak = 1 where id = user_uuid;
    elsif (streak_record.last_visit::date < now()::date) then
        update public.user_streaks
        set current_streak = current_streak + 1,
            longest_streak = greatest(longest_streak, current_streak + 1),
            last_visit = now()
        where user_id = user_uuid returning * into streak_record;
        update public.users set streak = streak_record.current_streak where id = user_uuid;
    else
        update public.user_streaks set last_visit = now()
        where user_id = user_uuid returning * into streak_record;
    end if;
    return streak_record;
end;$function$;

create or replace function public.check_quiz_session_before_insert()
returns trigger language plpgsql as $function$
declare
    max_attempt int;
begin
    if exists (
        select 1 from user_quiz_sessions
        where user_id = new.user_id and quiz_id = new.quiz_id and status = 'in_progress'
    ) then
        raise exception 'User already has an in-progress session for this quiz. Please complete or abandon the existing session first.'
            using errcode = '23505';
    end if;
    select coalesce(max(attempt_number), 0) into max_attempt
    from user_quiz_sessions where user_id = new.user_id and quiz_id = new.quiz_id;
    new.attempt_number := max_attempt + 1;
    return new;
end;
$function$;

create or replace function public.create_user_on_signup()
returns trigger language plpgsql security definer as $function$
begin
  insert into public.users (id, name, email, age, level, payment_plan, total_points, streak, joined_at)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'user_name', ''),
    new.email,
    coalesce((new.raw_user_meta_data->>'age')::int, 0),
    0, 0, 0, 0, new.created_at
  );
  return new;
end;
$function$;

create or replace function public.delete_user_cascade()
returns trigger language plpgsql security definer as $function$
begin
    delete from auth.users where id = old.id;
    return old;
end;
$function$;

create or replace function public.handle_new_public_user()
returns trigger language plpgsql security definer as $function$
begin
  insert into public.user_streaks (user_id, current_streak, last_visit)
  values (new.id, 0, now());
  return new;
